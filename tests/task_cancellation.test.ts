import { it } from "node:test";
import * as assert from "node:assert/strict";
import { AnstsSchedulerCell } from "../src/cloudflare/scheduler_cell.js";
import { MockDurableObjectState } from "../src/cloudflare/env.js";
import { NodeDaemon } from "../src/node_daemon.js";
it("persists queued cancellation and running cancellation intent without freeing a leased slot", async () => {
  const state = new MockDurableObjectState("cancel");
  let cell = new AnstsSchedulerCell(state);
  const post = (route: string, body: unknown) => cell.fetch(new Request("https://cell/v1/scheduler/" + route, { method: "POST", body: JSON.stringify(body) }));
  const cancel = (id: string) => post("cancel", { task_id: id, tenant_id: "tenant", actor: "user-a", reason: "stop work" });
  for (const id of ["queued", "running", "next"]) await post("submit", { task_id: id, tenant_id: "tenant", prompt: id, priority: 2 });
  assert.equal((await post("cancel", { task_id: "queued", tenant_id: "other", actor: "user-a", reason: "stop" })).status, 404);
  assert.equal((await cancel("queued")).status, 200);
  cell = new AnstsSchedulerCell(state);
  assert.equal(cell.scheduler.allTasks.get("queued")?.execution_outcome, "CANCELLED");
  const heartbeat = { ...new NodeDaemon("host").emitHeartbeat(), execution_slots: 1 };
  await post("register-node", heartbeat);
  const { placements } = await (await post("schedule-tick", {})).json();
  assert.equal(placements.length, 1);
  const [task_id, node_id, fencing_token] = placements[0];
  assert.notEqual(task_id, "queued");
  assert.equal((await cancel(task_id)).status, 200);
  cell = new AnstsSchedulerCell(state);
  assert.equal(cell.scheduler.allTasks.get(task_id)?.state, "LEASED");
  assert.equal((await (await post("lease-renew", { task_id, node_id, fencing_token })).json()).cancel_requested.actor, "user-a");
  await post("register-node", heartbeat);
  assert.equal((await (await post("schedule-tick", {})).json()).placements.length, 0);
  assert.equal((await post("complete", { task_id, node_id: "wrong", fencing_token, execution_outcome: "CANCELLED" })).status, 409);
  const result = { task_id, node_id, fencing_token, execution_outcome: "CANCELLED" };
  assert.equal((await post("complete", result)).status, 200);
  assert.equal((await post("complete", result)).status, 200);
  assert.equal((await post("complete", { ...result, execution_outcome: "SUCCEEDED" })).status, 409);
  assert.equal((await (await post("schedule-tick", {})).json()).placements.length, 1);
});
